static bool_t
Appt_2_before(XDR *xdrs, void *node)
{
	Appt_2 *objp = node;

	if (!_DtCm_xdr_Id_2 (xdrs, &objp->appt_id))
		return (FALSE);
	if (!_DtCm_xdr_Tag_2 (xdrs, &objp->tag))
		return (FALSE);
	if (!xdr_int (xdrs, &objp->duration))
		return (FALSE);
	if (!xdr_int (xdrs, &objp->ntimes))
		return (FALSE);
	if (!_DtCm_xdr_limited_string(xdrs, &objp->what, _DtCM_LIMIT_TEXT))
		return (FALSE);
	if (!_DtCm_xdr_limited_string(xdrs, &objp->mailto, _DtCM_LIMIT_TEXT))
		return (FALSE);
	if (!_DtCm_xdr_limited_string(xdrs, &objp->script, _DtCM_LIMIT_TEXT))
		return (FALSE);
	if (!_DtCm_xdr_Period_2 (xdrs, &objp->period))
		return (FALSE);
	if (!_DtCm_xdr_limited_string(xdrs, &objp->author, _DtCM_LIMIT_TEXT))
		return (FALSE);
	if (!_DtCm_xdr_limited_string(xdrs, &objp->client_data, _DtCM_LIMIT_TEXT))
		return (FALSE);
	if (!xdr_pointer (xdrs, (char **)&objp->exception, sizeof (Except_2), (xdrproc_t) _DtCm_xdr_Except_2))
		return (FALSE);
	if (!xdr_pointer (xdrs, (char **)&objp->attr, sizeof (Attribute_2), (xdrproc_t) _DtCm_xdr_Attribute_2))
		return (FALSE);
	return (TRUE);
}

