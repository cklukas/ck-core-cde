/*
 * XDR routines of version 2 of the calendar protocol (rtable2.x).
 *
 * The routines were first generated by rpcgen and are maintained here.
 * They differ from the generated ones in three ways: strings and lists have
 * the limits of cmlimits.h, the values of enumerations are checked, and the
 * nodes of a linked list are coded in a loop (see cmxdrlist.h) with the same
 * bytes on the wire, so the length of a list from the network cannot make
 * the decoder allocate without bound or nest without bound.
 */

#include <EUSCompat.h>

#include "rtable2.h"
#include "cmxdrlist.h"

/* An enumeration of the protocol has the values 0 to MAXIMUM. */
static bool_t
xdr_enum_to(XDR *xdrs, enum_t *objp, enum_t maximum)
{
	if (!xdr_enum(xdrs, objp))
		return (FALSE);
	if (xdrs->x_op == XDR_DECODE && (*objp < 0 || *objp > maximum))
		return (FALSE);
	return (TRUE);
}

